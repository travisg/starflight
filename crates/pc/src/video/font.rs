static GLYPHS: LazyLock<[[u8; 8]; 256]> = LazyLock::new(|| {
    let mut t = [[0u8; 8]; 256];
    for (code, g) in t.iter_mut().enumerate() {
        if let Some((_, e)) = EXTRA.iter().find(|(c, _)| *c as usize == code) {
            *g = *e;
            continue;
        }
        let ch = CP437[code];
        let found = BASIC_FONTS
            .get(ch)
            .or_else(|| LATIN_FONTS.get(ch))
            .or_else(|| BOX_FONTS.get(ch))
            .or_else(|| BLOCK_FONTS.get(ch))
            .or_else(|| GREEK_FONTS.get(ch))
            .or_else(|| MISC_FONTS.get(ch));
        // font8x8 stores the leftmost pixel in bit 0.
        if let Some(rows) = found {
            *g = rows.map(u8::reverse_bits);
        }
    }
    t
});

pub fn glyph(code: u8) -> &'static [u8; 8] {
    &GLYPHS[code as usize]
}

/// The code whose glyph is exactly `rows`, as INT 10h AH=08h finds it in
/// graphics modes.
pub fn find(rows: &[u8; 8]) -> Option<u8> {
    GLYPHS.iter().position(|g| g == rows).map(|c| c as u8)
}
